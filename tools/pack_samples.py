#!/usr/bin/env python3
"""Pack samples/*.wav into core/samples/sample_data.cpp (const arrays: flash on the ESP32-S3).

Reads samples/manifest.csv. Any WAV works: it is mixed to mono, resampled to 22,050 Hz and
stored as int16. Loop points in the manifest are in samples of the source file.
The four drums must be named kick, snare, hat, crash. Every other row is an instrument, listed
in manifest order. Standard library only.

    python tools/pack_samples.py
"""
import array
import csv
import sys
import wave
from pathlib import Path

RATE = 22050
REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "samples"
DEST = REPO / "core" / "samples" / "sample_data.cpp"
DRUMS = ["kick", "snare", "hat", "crash"]
FLASH_BUDGET = 1_500_000  # bytes; the app partition is 3 MB and holds the code too


def load(path):
    with wave.open(str(path), "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width == 2:
        a = array.array("h", raw)
        scale = 1.0
    elif width == 1:
        a = [b - 128 for b in raw]
        scale = 256.0
    elif width in (3, 4):
        a = [int.from_bytes(raw[i:i + width], "little", signed=True) for i in range(0, len(raw), width)]
        scale = 1.0 / (1 << (8 * width - 16))
    else:
        sys.exit(f"{path}: unsupported sample width {width}")
    mono = [sum(a[i * ch + c] for c in range(ch)) * scale / ch for i in range(n)]
    return mono, rate


def resample(x, src_rate):
    if src_rate == RATE:
        return x, 1.0
    ratio = src_rate / RATE
    n = int(len(x) / ratio)
    out = []
    for i in range(n):
        p = i * ratio
        k = int(p)
        f = p - k
        b = x[k + 1] if k + 1 < len(x) else 0.0
        out.append(x[k] + (b - x[k]) * f)
    return out, 1.0 / ratio


def main():
    rows = list(csv.DictReader(open(SRC / "manifest.csv", newline="")))
    names = [r["name"] for r in rows]
    for d in DRUMS:
        if d not in names:
            sys.exit(f"manifest needs a drum named {d}")
    insts = [r for r in rows if r["name"] not in DRUMS]
    if not insts:
        sys.exit("manifest needs at least one instrument")

    total = 0
    body = []
    table = []
    for r in rows:
        x, rate = load(SRC / r["file"])
        x, k = resample(x, rate)
        ls, le = int(int(r["loop_start"]) * k), int(int(r["loop_end"]) * k)
        if le <= ls or le > len(x):
            ls = le = 0
        data = [max(-32768, min(32767, int(round(v)))) for v in x]
        total += len(data) * 2
        ident = "k_" + "".join(c if c.isalnum() else "_" for c in r["name"])
        lines = [", ".join(str(v) for v in data[i:i + 24]) for i in range(0, len(data), 24)]
        body.append(f"const int16_t {ident}[{len(data)}] = {{\n" + ",\n".join(lines) + "};\n")
        table.append((r, ident, len(data), ls, le))

    if total > FLASH_BUDGET:
        sys.exit(f"samples take {total} bytes, over the {FLASH_BUDGET} byte budget")

    def entry(r, ident, n, ls, le):
        name = r["name"].upper()[:10]
        return (f'    {{"{name}", {ident}, {n}u, {ls}u, {le}u, {int(r["root"])}, {float(r["release_s"]):.4f}f}}')

    by_name = {t[0]["name"]: t for t in table}
    out = [
        "// GENERATED by tools/pack_samples.py from samples/. Do not edit.",
        f"// {len(table)} samples, {total} bytes, {RATE} Hz mono int16.",
        '#include "core/samples/samples.hpp"',
        "",
        "namespace danger {",
        "namespace {",
        "",
        *body,
        "}  // namespace",
        "",
        "const Sample kDrumSamples[kDrumCount] = {",
        ",\n".join(entry(*by_name[d]) for d in DRUMS),
        "};",
        "",
        f"const Sample kInstrumentSamples[{len(insts)}] = {{",
        ",\n".join(entry(*by_name[r["name"]]) for r in insts),
        "};",
        f"const int kInstrumentCount = {len(insts)};",
        "",
        "}  // namespace danger",
        "",
    ]
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(out))
    print(f"wrote {DEST.relative_to(REPO)}: {len(table)} samples, {total} bytes")


if __name__ == "__main__":
    main()
